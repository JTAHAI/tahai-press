export const SVELTIA_CMS_VERSION = '0.164.2';
export const SVELTIA_CMS_LICENSE = 'MIT';
export const SVELTIA_CMS_SCRIPT = `https://unpkg.com/@sveltia/cms@${SVELTIA_CMS_VERSION}/dist/sveltia-cms.js`;

const REPOSITORY_SLUG = /^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/;
const ARTICLE_TYPES = new Set(['standard', 'pdf', 'mixed', 'external']);
const CLASSIFICATIONS = new Set(['news', 'analysis', 'opinion', 'investigation', 'public-record', 'explainer', 'interview', 'announcement', 'developing']);

function clean(value, fallback = '') {
  const text = String(value ?? '').trim();
  return text || fallback;
}

export function repositorySlugFromUrl(value) {
  const raw = clean(value);
  if (!raw) return '';
  if (REPOSITORY_SLUG.test(raw)) return raw.replace(/\.git$/i, '');

  const ssh = raw.match(/^(?:ssh:\/\/)?git@[^:]+:(.+?)(?:\.git)?$/i);
  if (ssh?.[1] && REPOSITORY_SLUG.test(ssh[1])) return ssh[1];

  try {
    const url = new URL(raw);
    const slug = url.pathname.replace(/^\/+|\/+$/g, '').replace(/\.git$/i, '');
    return REPOSITORY_SLUG.test(slug) ? slug : '';
  } catch {
    return '';
  }
}

export function cmsRepository(env = process.env, packageInfo = {}) {
  const configured = clean(env.TAHAI_PRESS_CMS_REPO);
  const packageUrl = typeof packageInfo.repository === 'string'
    ? packageInfo.repository
    : packageInfo.repository?.url;
  const resolved = repositorySlugFromUrl(configured || packageUrl);
  if (!resolved) {
    throw new Error('Unable to determine the Git CMS repository. Set TAHAI_PRESS_CMS_REPO to owner/repository.');
  }
  return resolved;
}

export function cmsBranch(env = process.env) {
  const branch = clean(env.TAHAI_PRESS_CMS_BRANCH || env.PUBLICATION_PRODUCTION_BRANCH, 'main');
  if (!/^[A-Za-z0-9._/-]+$/.test(branch) || branch.includes('..') || branch.startsWith('/') || branch.endsWith('/')) {
    throw new Error('TAHAI_PRESS_CMS_BRANCH contains unsupported characters.');
  }
  return branch;
}

