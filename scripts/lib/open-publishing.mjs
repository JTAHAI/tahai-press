export function normalizeNewsroomDraft(record = {}) {
  const draft = structuredClone(record);
  draft.title = clean(draft.title);
  draft.slug = clean(draft.slug);
  draft.status = 'draft';
  draft.article_type = ARTICLE_TYPES.has(draft.article_type) ? draft.article_type : 'standard';
  draft.classification = CLASSIFICATIONS.has(draft.classification) ? draft.classification : 'news';
  draft.excerpt = clean(draft.excerpt);
  draft.body = clean(draft.body);
  draft.author = clean(draft.author);
  draft.categories = Array.isArray(draft.categories) ? draft.categories.map((item) => clean(item)).filter(Boolean) : [];
  draft.tags = Array.isArray(draft.tags) ? draft.tags.map((item) => clean(item)).filter(Boolean) : [];
  draft.featured = draft.featured === true;
  draft.review_content = draft.review_content === true;
  draft.review_rights = draft.review_rights === true;
  draft.review_accessibility = draft.review_accessibility === true;
  for (const field of ['featured_image', 'featured_image_alt', 'featured_image_caption', 'featured_image_credit', 'featured_image_rights', 'published_at', 'kicker', 'editor_notes']) {
    if (draft[field] !== undefined) draft[field] = clean(draft[field]);
  }
  if (!draft.featured_image) {
    for (const field of ['featured_image', 'featured_image_alt', 'featured_image_caption', 'featured_image_credit', 'featured_image_rights']) delete draft[field];
  }
  if (!draft.published_at) delete draft.published_at;
  if (!draft.kicker) delete draft.kicker;
  if (!draft.editor_notes) delete draft.editor_notes;
  if (!Array.isArray(draft.source_links) || !draft.source_links.length) delete draft.source_links;
  return draft;
}

export function newsroomDraftErrors(record = {}) {
  const draft = normalizeNewsroomDraft(record);
  const errors = [];
  if (!draft.title) errors.push('title is required');
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(draft.slug)) errors.push('slug must use lowercase letters, numbers, and single hyphens');
  if (draft.excerpt.length < 20 || draft.excerpt.length > 360) errors.push('excerpt must be between 20 and 360 characters');
  if (!draft.body) errors.push('body is required');
  if (!draft.author) errors.push('author is required');
  if (!draft.categories.length || draft.categories.length > 5) errors.push('categories must contain one to five slugs');
  if (draft.featured_image && !draft.featured_image_alt) errors.push('featured_image_alt is required when featured_image is set');
  return errors;
}

export function promotionDestination(root, slug) {
  return path.join(root, 'content', 'articles', `${slug}.json`);
}
